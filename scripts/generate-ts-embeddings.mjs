import fs from 'fs';

// Read the embeddings output
const embeddings = JSON.parse(fs.readFileSync('scripts/embeddings-output.json', 'utf8'));

// Round embeddings to 5 decimal places to reduce file size
function roundEmbedding(embedding) {
  return embedding.map(v => Math.round(v * 100000) / 100000);
}

// Group by cluster for color palette
const clusterData = {};
embeddings.forEach(node => {
  if (!clusterData[node.cluster]) {
    clusterData[node.cluster] = {
      color: node.color,
      nodeIds: []
    };
  }
  clusterData[node.cluster].nodeIds.push(node.id);
});

// Generate shared/embeddings.ts
let embeddingsTS = `// Auto-generated by scripts/generate-ts-embeddings.mjs
// DO NOT EDIT MANUALLY - regenerate using: node scripts/generate-embeddings.mjs && node scripts/generate-ts-embeddings.mjs

export interface NodeEmbeddingData {
  embedding: number[];
  clusterId: number;
  categoryColor: string;
}

export const nodeEmbeddings: Record<string, NodeEmbeddingData> = {
`;

// Add each node's embedding
embeddings.forEach((node, index) => {
  const roundedEmbedding = roundEmbedding(node.embedding);
  embeddingsTS += `  '${node.id}': {\n`;
  embeddingsTS += `    clusterId: ${node.cluster},\n`;
  embeddingsTS += `    categoryColor: '${node.color}',\n`;
  embeddingsTS += `    embedding: [\n`;
  
  // Format embedding array with 10 values per line
  for (let i = 0; i < roundedEmbedding.length; i += 10) {
    const chunk = roundedEmbedding.slice(i, i + 10);
    embeddingsTS += `      ${chunk.join(', ')}`;
    if (i + 10 < roundedEmbedding.length) {
      embeddingsTS += ',\n';
    } else {
      embeddingsTS += '\n';
    }
  }
  
  embeddingsTS += `    ]\n`;
  embeddingsTS += `  }${index < embeddings.length - 1 ? ',' : ''}\n`;
});

embeddingsTS += `};\n`;

// Write embeddings file
fs.writeFileSync('shared/embeddings.ts', embeddingsTS);
console.log('✅ Generated shared/embeddings.ts');

// Generate shared/cluster-colors.ts
let clusterColorsTS = `// Auto-generated by scripts/generate-ts-embeddings.mjs
// DO NOT EDIT MANUALLY - regenerate using: node scripts/generate-embeddings.mjs && node scripts/generate-ts-embeddings.mjs

export interface ClusterInfo {
  id: number;
  color: string;
  nodeIds: string[];
}

export const clusterPalette = [
  '#8CCB9B', // Cluster 0: Green - TV/Sports/Tech/Social
  '#F5C06E', // Cluster 1: Yellow - Food/Dining/Shows
  '#9C8ADE', // Cluster 2: Purple - Music/Arts/Travel
  '#74A8E4', // Cluster 3: Blue - Fitness/Health
  '#E7A26F', // Cluster 4: Orange - Lifestyle/Decor/Tech
  '#F28B82', // Cluster 5: Red - Wellness/Fitness
];

export const clusters: ClusterInfo[] = [
`;

// Add cluster info
Object.entries(clusterData)
  .sort((a, b) => parseInt(a[0]) - parseInt(b[0]))
  .forEach(([clusterId, data], index) => {
    clusterColorsTS += `  {\n`;
    clusterColorsTS += `    id: ${clusterId},\n`;
    clusterColorsTS += `    color: '${data.color}',\n`;
    clusterColorsTS += `    nodeIds: [\n`;
    
    // Group node IDs into lines
    const ids = data.nodeIds;
    for (let i = 0; i < ids.length; i += 8) {
      const chunk = ids.slice(i, i + 8);
      clusterColorsTS += `      ${chunk.map(id => `'${id}'`).join(', ')}`;
      if (i + 8 < ids.length) {
        clusterColorsTS += ',\n';
      } else {
        clusterColorsTS += '\n';
      }
    }
    
    clusterColorsTS += `    ]\n`;
    clusterColorsTS += `  }${index < Object.keys(clusterData).length - 1 ? ',' : ''}\n`;
  });

clusterColorsTS += `];\n\n`;
clusterColorsTS += `export function getClusterColor(clusterId: number): string {
  return clusterPalette[clusterId] || clusterPalette[0];
}\n`;

// Write cluster colors file
fs.writeFileSync('shared/cluster-colors.ts', clusterColorsTS);
console.log('✅ Generated shared/cluster-colors.ts');

// Generate helper function in a separate file
const helperTS = `// Helper function to augment nodes with embedding data
import { nodeEmbeddings } from './embeddings';
import type { Node } from './synthetic-data';

export function augmentNodesWithEmbeddings<T extends Node>(nodes: T[]): T[] {
  return nodes.map(node => {
    const embeddingData = nodeEmbeddings[node.id];
    if (embeddingData) {
      return {
        ...node,
        embedding: embeddingData.embedding,
        clusterId: embeddingData.clusterId,
        categoryColor: embeddingData.categoryColor,
      };
    }
    return node;
  });
}

// Cosine similarity helper for semantic matching
export function cosineSimilarity(a: number[], b: number[]): number {
  if (a.length !== b.length) return 0;
  
  let dotProduct = 0;
  let normA = 0;
  let normB = 0;
  
  for (let i = 0; i < a.length; i++) {
    dotProduct += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }
  
  return dotProduct / (Math.sqrt(normA) * Math.sqrt(normB));
}
`;

fs.writeFileSync('shared/embedding-helpers.ts', helperTS);
console.log('✅ Generated shared/embedding-helpers.ts');

